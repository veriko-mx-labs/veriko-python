"""Generates `src/veriko/_async_resources.py` from `src/veriko/resources.py`.

Run it after changing the public methods of a family:

    python scripts/generate_async.py

`tests/test_async_client.py` fails when the generated file is out of date.
Each public method of a family becomes a coroutine that runs the synchronous
method in a worker thread; iterators become asynchronous iterators.
"""

