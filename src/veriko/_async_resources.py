async def _run(function: Any, *args: Any, **kwargs: Any) -> Any:
    return await asyncio.to_thread(functools.partial(function, *args, **kwargs))


async def _aiter(iterator: Iterator[T]) -> AsyncIterator[T]:
    sentinel = object()
    while True:
        item = await asyncio.to_thread(next, iterator, sentinel)
        if item is sentinel:
            return
        yield item  # type: ignore[misc]


