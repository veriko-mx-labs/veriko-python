"""Official Veriko SDK for Python.

Veriko validates Mexican SPEI transfers against the CEP (Comprobante Electrónico
de Pago) that the Banco de México issues, and returns a verdict.

    from veriko import Veriko

    client = Veriko()  # reads VERIKO_API_KEY from the environment

    validation = client.validate_transfer(
        send_date="2025-03-15",
        amount=15000.50,
        tracking_key="MXBA20250315001234",
        beneficiary_account="012180004412345678",
    )

    if validation.status == "valid":
        cep = client.get_cep(validation.id, format="pdf")
        cep.write_to(cep.filename)

API documentation: https://docs.veriko.mx/en/
"""

